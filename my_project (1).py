from scipy import stats
import numpy as np


models = {

          'Logistic Regression': LogisticRegression(solver='liblinear'),
          'Random Forest':RandomForestClassifier(),
          'SVM':SVC(),
          'XGBoost': XGBClassifier()
}

cv_scores = {}

for model_name, model in models.items():
    scores = cross_val_score(model, x, y, cv=kf, scoring='accuracy')
    cv_scores[model_name] = scores


log_reg_scores = cv_scores['Logistic Regression']
rf_scores = cv_scores['Random Forest']
svm_scores = cv_scores['SVM']
xgb_scores = cv_scores['XGBoost']

# One-way ANOVA Test
f_stat, p_value = stats.f_oneway(log_reg_scores, rf_scores, svm_scores, xgb_scores)
print(f"F-statistics: {f_stat:.4f}, p-value: {p_value:.4f}")

